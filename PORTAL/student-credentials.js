// Helper function to authenticate student
export function authenticateStudent(username, password) {
  const norm = s => s.toLowerCase().replace(/\s+/g, ' ').trim();
  const inputKey = norm(username);
  let matchedKey = null;
  for (const key in studentCredentials) {
    if (norm(key) === inputKey) {
      matchedKey = key;
      break;
    }
  }
  if (!matchedKey) {
    return { success: false, message: "Student not found" };
  }
  
  const student = studentCredentials[matchedKey];
  if (student.password !== password) {
    return { success: false, message: "Incorrect password" };
  }
  
  return {
    success: true,
    message: "Login successful",
    data: {
      name: matchedKey,
      class: student.class,
      studentId: student.studentId,
      email: student.email,
      role: "student"
    }
  };
}

// Helper function to get student info
export function getStudentInfo(username) {
  const student = studentCredentials[username];
  if (!student) return null;
  
  return {
    name: username,
    class: student.class,
    studentId: student.studentId,
    email: student.email,
    role: "student"
  };
}
